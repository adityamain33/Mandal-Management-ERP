aartiCollections.forEach((col) => {
  const filePath = path.join(outputDir, col.fileName);
  const doc = new PDFDocument({
    size: 'A4',
    margin: 36,
    info: {
      Title: col.title,
      Author: 'MandalSetu ERP',
      Subject: col.subtitle,
    }
  });

  const writeStream = fs.createWriteStream(filePath);
  doc.pipe(writeStream);

  if (fontToUse) {
    doc.registerFont('DevaFont', fontToUse);
    doc.font('DevaFont');
  }

  // Draw Decorative Outer Border
  doc.rect(18, 18, doc.page.width - 36, doc.page.height - 36).lineWidth(2).stroke(col.themeColor);
  doc.rect(22, 22, doc.page.width - 44, doc.page.height - 44).lineWidth(0.8).stroke('#f59e0b');

  // Top Header Banner
  doc.fillColor(col.themeColor).fontSize(18).text(col.title, { align: 'center' });
  doc.moveDown(0.2);
  doc.fillColor('#64748b').fontSize(10).text(col.subtitle, { align: 'center' });
  doc.moveDown(0.4);

  // Decorative line
  doc.moveTo(36, doc.y).lineTo(doc.page.width - 36, doc.y).lineWidth(1).stroke(col.themeColor);
  doc.moveDown(0.6);

  col.items.forEach((item, index) => {
    // Check page space
    if (doc.y > doc.page.height - 150) {
      doc.addPage();
      if (fontToUse) doc.font('DevaFont');
      doc.rect(18, 18, doc.page.width - 36, doc.page.height - 36).lineWidth(2).stroke(col.themeColor);
      doc.rect(22, 22, doc.page.width - 44, doc.page.height - 44).lineWidth(0.8).stroke('#f59e0b');
    }

    doc.fillColor(col.themeColor).fontSize(13).text(item.name, { align: 'left' });
    if (item.rushi) {
      doc.fillColor('#94a3b8').fontSize(9).text(item.rushi, { align: 'left' });
    }
    doc.moveDown(0.3);

    doc.fillColor('#1e293b').fontSize(11).lineGap(4).text(item.content, {
      align: 'left',
      indent: 10,
    });
    doc.moveDown(0.8);
  });

  // Footer
  doc.fontSize(8).fillColor('#94a3b8').text('MandalSetu ERP • www.mandalsetu.com • सर्व हक्क सुरक्षित', 36, doc.page.height - 32, {
    align: 'center',
    width: doc.page.width - 72,
  });

  doc.end();
  console.log(`Generated: ${col.fileName}`);
});
